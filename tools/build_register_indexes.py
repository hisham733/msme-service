#!/usr/bin/env python3
"""Regenerate decisions/INDEX.md and todo/INDEX.md from OKF front-matter.

Also keeps each `todo/T-*.md` file's **name and heading** in sync with its `status:`:
`T-050.md` -> `🟢 T-050.md` and `## 🟢 T-050 ...`. References to the old filename in
`docs/`, `decisions/`, `todo/` and `session-analysis/` are rewritten in the same run.
Exits non-zero (writing nothing for the failed register) when an item is malformed.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTE = "_Generated by `build_register_indexes.py` — do not hand-edit._"

# One icon per status, used by the todo index (and available to any register).
STATUS_ICON = {
    "open": "🟢",
    "in-progress": "🚧",
    "awaiting-user": "⏳",
    "awaiting-MG": "⏳",
    "parked": "⏸️",
    "closed": "✅",
    "decided": "✅",
    "decided-unbuilt": "🔨",
    "superseded": "🗑️",
    "blocked": "⛔",
}


def status_with_icon(status: str) -> str:
    """`open` -> `🟢 open`; an unknown status keeps a neutral dot."""
    return f"{STATUS_ICON.get(status, '•')} {status}"


HEADING = re.compile(r"^##\s+(?:[^\w\s]+\s*)?(.*)$")
ICON_PREFIX = re.compile(r"^(?:[^\w\s]+\s*)?")


def _icon(status: str) -> str:
    return STATUS_ICON.get(status, "•")


def target_name(old_name: str, status: str) -> str:
    """`T-050.md` -> `🟢 T-050.md`; an already-iconed name is re-prefixed for the status."""
    base = ICON_PREFIX.sub("", Path(old_name).stem)
    return f"{_icon(status)} {base}.md"


def sync_item(path: Path, item: dict) -> Path:
    """Rename the file to `<icon> T-xxx.md` and put the same icon on its first heading."""
    target = path.with_name(target_name(path.name, item["status"]))
    if target != path:
        if target.exists():
            raise ValueError(f"target already exists: {target.name}")
        path.rename(target)
        path = target
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return path
    icon = _icon(item["status"])
    for i in range(end + 1, len(lines)):
        if lines[i].startswith("## "):
            match = HEADING.match(lines[i])
            if match:
                new = f"## {icon} {match.group(1)}"
                if new != lines[i]:
                    lines[i] = new
                    path.write_text("\n".join(lines) + ("\n" if text.endswith("\n") else ""),
                                    encoding="utf-8")
            break
    return path


def update_references(renames: dict) -> int:
    """Rewrite old todo filenames in current docs/registers and replies; returns files changed."""
    if not renames:
        return 0
    files = [ROOT / "README.md", ROOT / "NOW.md", ROOT / "AGENTS.md", ROOT / "INDEX.md"]
    for folder in ("docs", "decisions", "todo", "session-analysis"):
        files += [p for p in (ROOT / folder).rglob("*.md")
                  if not (folder == "todo" and p.name == "INDEX.md")]
    changed = 0
    for path in files:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        before = text
        for old, new in renames.items():
            text = text.replace(old, new)
        if text != before:
            path.write_text(text, encoding="utf-8")
            changed += 1
    return changed


def _parse(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path.name}: missing front-matter")
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip()
    for key in ("id", "title", "status"):
        if key not in meta:
            raise ValueError(f"{path.name}: missing required key '{key}'")
    return meta


def _num(item_id: str) -> int:
    digits = re.sub(r"\D", "", item_id)
    return int(digits) if digits else 0


def load(folder: Path) -> list:
    items = []
    for path in sorted(folder.glob("*.md")):
        if path.name == "INDEX.md":
            continue
        meta = _parse(path)
        meta["_file"] = path.name
        items.append(meta)
    ids = [m["id"] for m in items]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise ValueError(f"duplicate ids: {', '.join(dupes)}")
    return sorted(items, key=lambda m: _num(m["id"]))


def write_index(path: Path, title: str, sections, legend: str = "") -> None:
    out = [f"# {title} — INDEX", "", NOTE]
    if legend:
        out += ["", legend]
    out.append("")
    for header, items, columns in sections:
        out.append(f"## {header}")
        out.append("")
        out.append("| " + " | ".join(columns) + " |")
        out.append("|" + "---|" * len(columns))
        for m in items:
            row = []
            for col in columns:
                if col == "file":
                    row.append(f"[{m['_file']}]({m['_file']})")
                else:
                    row.append(m.get(col, "—"))
            out.append("| " + " | ".join(row) + " |")
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    try:
        decisions = load(ROOT / "decisions")
        todos = load(ROOT / "todo")
    except ValueError as exc:
        print(f"FAIL: {exc}")
        return 1

    live_statuses = ("open", "awaiting-user", "awaiting-MG", "in-progress", "blocked")
    renames = {t["_file"]: target_name(t["_file"], t["status"]) for t in todos}
    renames = {old: new for old, new in renames.items() if old != new}
    refs_changed = update_references(renames)
    for t in todos:
        new_path = sync_item(ROOT / "todo" / t["_file"], t)
        t["_file"] = new_path.name
    live = [t for t in todos if t["status"] in live_statuses]
    other = [t for t in todos if t["status"] not in live_statuses]

    write_index(
        ROOT / "decisions" / "INDEX.md",
        "decisions",
        [("All decisions", decisions, ["id", "title", "status", "date", "area", "file"])],
    )
    write_index(
        ROOT / "todo" / "INDEX.md",
        "todo",
        [
            ("Live", live, ["id", "title", "status", "area", "raised", "file"]),
            ("Parked / closed", other, ["id", "title", "status", "area", "raised", "file"]),
        ],
        legend=("_Icons: 🟢 open · 🚧 in progress · ⏳ awaiting user · ⏸️ parked · "
                "✅ closed · 🔨 decided-unbuilt · 🗑️ superseded · ⛔ blocked._"),
    )

    d_status = {}
    for m in decisions:
        d_status[m["status"]] = d_status.get(m["status"], 0) + 1
    t_status = {}
    for m in todos:
        t_status[m["status"]] = t_status.get(m["status"], 0) + 1
    print(f"OK: decisions={len(decisions)} {d_status}; todo={len(todos)} {t_status}; "
          f"live={len(live)}; renamed={len(renames)}; refs={refs_changed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
