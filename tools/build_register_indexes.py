#!/usr/bin/env python3
"""Regenerate decisions/INDEX.md and todo/INDEX.md from OKF front-matter.

Read-only for the register items; writes only the two generated INDEX files.
Exits non-zero (writing nothing for the failed register) when an item is malformed.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTE = "_Generated by `build_register_indexes.py` — do not hand-edit._"


def _parse(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path.name}: missing front-matter")
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip()
    for key in ("id", "title", "status"):
        if key not in meta:
            raise ValueError(f"{path.name}: missing required key '{key}'")
    return meta


def _num(item_id: str) -> int:
    digits = re.sub(r"\D", "", item_id)
    return int(digits) if digits else 0


def load(folder: Path) -> list:
    items = []
    for path in sorted(folder.glob("*.md")):
        if path.name == "INDEX.md":
            continue
        meta = _parse(path)
        meta["_file"] = path.name
        items.append(meta)
    ids = [m["id"] for m in items]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise ValueError(f"duplicate ids: {', '.join(dupes)}")
    return sorted(items, key=lambda m: _num(m["id"]))


def write_index(path: Path, title: str, sections) -> None:
    out = [f"# {title} — INDEX", "", NOTE, ""]
    for header, items, columns in sections:
        out.append(f"## {header}")
        out.append("")
        out.append("| " + " | ".join(columns) + " |")
        out.append("|" + "---|" * len(columns))
        for m in items:
            row = []
            for col in columns:
                if col == "file":
                    row.append(f"[{m['id']}]({m['_file']})")
                else:
                    row.append(m.get(col, "—"))
            out.append("| " + " | ".join(row) + " |")
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    try:
        decisions = load(ROOT / "decisions")
        todos = load(ROOT / "todo")
    except ValueError as exc:
        print(f"FAIL: {exc}")
        return 1

    live = [t for t in todos if t["status"] in ("open", "awaiting-MG")]
    other = [t for t in todos if t["status"] not in ("open", "awaiting-MG")]

    write_index(
        ROOT / "decisions" / "INDEX.md",
        "decisions",
        [("All decisions", decisions, ["id", "title", "status", "date", "area", "file"])],
    )
    write_index(
        ROOT / "todo" / "INDEX.md",
        "todo",
        [
            ("Live", live, ["id", "title", "status", "area", "raised", "file"]),
            ("Parked / closed", other, ["id", "title", "status", "area", "raised", "file"]),
        ],
    )

    d_status = {}
    for m in decisions:
        d_status[m["status"]] = d_status.get(m["status"], 0) + 1
    t_status = {}
    for m in todos:
        t_status[m["status"]] = t_status.get(m["status"], 0) + 1
    print(f"OK: decisions={len(decisions)} {d_status}; todo={len(todos)} {t_status}; live={len(live)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
